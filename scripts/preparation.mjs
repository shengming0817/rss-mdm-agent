// ref: Git object-file.c@v2.51.0 (format_object_header / stream_object_signature)
// Frame both paths and payloads: embedded NUL/path bytes in file content cannot
// impersonate a subsequent entry, and links/directories have distinct types.
function hashEntry(digest, type, name, bytes = "") {
  const path = Buffer.from(name),
    content = Buffer.from(bytes);
  digest.update(`${type}\0${path.length}\0${content.length}\0`);
  digest.update(path);
  digest.update(content);
}
export function treeDigest(path) {
  const digest = createHash("sha256");
  function visit(current, name) {
    const stat = lstatSync(current);
    if (stat.isDirectory()) {
      hashEntry(digest, "dir", name);
      for (const child of readdirSync(current).sort())
        visit(join(current, child), `${name}/${child}`);
    } else if (stat.isFile())
      hashEntry(digest, "file", name, readFileSync(current));
    else if (stat.isSymbolicLink())
      hashEntry(digest, "link", name, readlinkSync(current));
    else throw Error(`unsupported prepared input: ${current}`);
  }
  visit(path, ".");
  return digest.digest("hex");
}
// Source bytes, including dirty/untracked inputs; outputs and dependency caches are excluded.
export function sourceDigest(directory) {
  const digest = createHash("sha256");
  function visit(name) {
    const path = join(directory, name);
    if (!existsSync(path)) return;
    const stat = lstatSync(path);
    if (stat.isDirectory()) {
      for (const child of readdirSync(path).sort()) {
        if (
          [
            "node_modules",
            "dist",
            "target",
            "gen",
            "autogenerated",
            "ai-host-runtime",
            "__pycache__",
          ].includes(child) ||
          child.endsWith(".tsbuildinfo")
        )
          continue;
        visit(`${name}/${child}`);
      }
    } else if (stat.isFile())
      hashEntry(digest, "file", name, readFileSync(path));
    else if (stat.isSymbolicLink())
      hashEntry(digest, "link", name, readlinkSync(path));
  }
  for (const name of [
    "Cargo.toml",
    "Cargo.lock",
    "rust-toolchain.toml",
    "package.json",
    "pnpm-lock.yaml",
    "pnpm-workspace.yaml",
    "tsconfig.json",
    "vitest.config.ts",
    ".npmrc",
    ".cargo",
    ".config",
    "schemas",
    "crates",
    "vendor",
    "packages",
    "apps",
    "scripts",
    "tests",
    "apps/desktop/src-tauri/resources/ai-host-runtime/manifest.json",
  ])
    visit(name);
  return digest.digest("hex");
}
function configuration(directory, env) {
  const inputs = Object.keys(env)
    .filter(
      (key) =>
        /^(CARGO_|RUST|TAURI_|VITE_)/.test(key) ||
        [
          "NODE_OPTIONS",
          "NODE_ENV",
          "RSS_BUILD_MDM_ORGANIZATION",
          "RSS_DESKTOP_ASSEMBLY",
        ].includes(key),
    )
    .sort();
  return JSON.stringify({
    target: cargoTargetDir(realpathSync(directory), env),
    ...Object.fromEntries(inputs.map((key) => [key, env[key]])),
  });
}
function toolchain(directory, env, names) {
  const read = (command, args) => {
    const invocation = resolveCommand(command, args, env);
    return execFileSync(invocation.command, invocation.args, {
      cwd: directory,
      env,
      encoding: "utf8",
      // ref: Node.js lib/child_process.js@v24.14.1 (spawnSync timeout/killSignal).
      timeout: 10000,
      killSignal: "SIGKILL",
    }).trim();
  };
  return {
    node: process.versions.node,
    ...Object.fromEntries(
      names
        .filter((name) => name !== "node")
        .map((name) => [
          name,
          read(name, name === "rustc" ? ["-vV"] : ["--version"]),
        ]),
    ),
  };
}
export function preparedContext(directory = root, env = process.env) {
  if (!env[contextKey])
    throw Error("prepared inputs required; use the owning pnpm/CI entry");
  const value = JSON.parse(env[contextKey]);
  if (
    value.root !== realpathSync(directory) ||
    !Number.isSafeInteger(value.owner) ||
    value.owner < 1 ||
    !existsSync(value.directory) ||
    dirname(value.directory) !== join(value.root, ".local-ci-runs")
  )
    throw Error("invalid or expired preparation context");
  try {
    process.kill(value.owner, 0);
  } catch {
    throw Error("preparation owner has exited");
  }
  if (
    value.config !== configuration(directory, env) ||
    value.source !== sourceDigest(directory)
  )
    throw Error("prepared inputs changed; start a new run");
  if (
    JSON.stringify(value.tools) !==
    JSON.stringify(toolchain(directory, env, Object.keys(value.tools)))
  )
    throw Error("prepared toolchain changed; start a new run");
  return value;
}
export function preparedArtifact(key, directory = root, env = process.env) {
  const value = preparedContext(directory, env);
  if (key.startsWith("node:")) {
    if (!value.nodes.includes(key.slice(5)))
      throw Error(`missing prepared Node selection: ${key}`);
    for (const [name, artifact] of Object.entries(value.artifacts)) {
      if (!name.startsWith("node:")) continue;
      if (
        !existsSync(artifact.path) ||
        treeDigest(artifact.path) !== artifact.digest
      )
        throw Error(`missing or changed prepared Node package: ${name}`);
    }
    return key === "node:*" ? directory : value.artifacts[key].path;
  }

  const artifact = value.artifacts[key];
  if (
    !artifact ||
    !existsSync(artifact.path) ||
    treeDigest(artifact.path) !== artifact.digest
  )
    throw Error(`missing or changed prepared artifact: ${key}`);
  return artifact.path;
}
export function preparedCheck(key, directory = root, env = process.env) {
  const value = preparedContext(directory, env);
  return value.checks.includes(key);
}
export function checkAlreadyPrepared(key) {
  return Boolean(process.env[contextKey]) && preparedCheck(key);
}
// Generators consume the helper's output; they do not own a build scheduler.
export async function helperOutput(key, args = []) {
  return withPreparation([key], (env) =>
    execFileSync(preparedArtifact(key), args, {
      cwd: root,
      env,
      encoding: "utf8",
      maxBuffer: 16 * 1024 * 1024,
    }),
  );
}
export class Preparation {
  constructor(
    directory = root,
    {
      env = process.env,
      signal,
      execute = runCommand,
      onPrepared = () => {},
      onCommand = () => {},
    } = {},
  ) {
    this.root = realpathSync(directory);
    this.baseEnv = { ...env };
    delete this.baseEnv[contextKey];
    this.signal = signal;
    this.execute = execute;
    this.onPrepared = onPrepared;
    this.onCommand = onCommand;
    this.tools = { node: process.versions.node };
    this.artifacts = {};
    this.nodes = new Set();
    this.checks = new Set();
    this.failures = new Map();
    this.directory = undefined;
    this.source = sourceDigest(directory);
    this.config = configuration(directory, this.baseEnv);
  }
  get env() {
    return {
      ...this.baseEnv,
      [contextKey]: JSON.stringify({
        root: this.root,
        owner: process.pid,
        directory: this.directory,
        source: this.source,
        config: this.config,
        tools: this.tools,
        artifacts: this.artifacts,
        nodes: [...this.nodes],
        checks: [...this.checks],
      }),
    };
  }
  assertInputs() {
    if (this.signal?.aborted) throw Error("preparation cancelled");
    if (
      sourceDigest(this.root) !== this.source ||
      configuration(this.root, this.baseEnv) !== this.config
    )
      throw Error("inputs changed during preparation/run");
    if (
      this.tools &&
      JSON.stringify(
        toolchain(this.root, this.baseEnv, Object.keys(this.tools)),
      ) !== JSON.stringify(this.tools)
    )
      throw Error("toolchain changed during preparation/run");
  }
  requireTools(names) {
    const missing = names.filter((name) => !this.tools[name]);
    if (!missing.length) return;
    Object.assign(this.tools, toolchain(this.root, this.baseEnv, missing));
    const manifest = JSON.parse(readFileSync(join(this.root, "package.json")));
    if (
      this.tools.node !== manifest.engines.node ||
      (this.tools.pnpm && `pnpm@${this.tools.pnpm}` !== manifest.packageManager)
    )
      throw Error("preparation requires the pinned Node/pnpm toolchain");
  }
  async command(command, args, capture = false, env = this.env) {
    ({ command, args } = resolveCommand(command, args, env));
    const start = performance.now();
    const result = await this.execute(command, args, {
      cwd: this.root,
      env,
      stdio: "inherit",
      signal: this.signal,
      capture,
    });
    this.onCommand({
      command: [command, ...args],
      status: result.status,
      signal: result.signal,
      durationMs: performance.now() - start,
    });
    if (result.status !== 0)
      throw Error(
        `${command} ${args.join(" ")}: ${result.error?.message ?? result.signal ?? result.status}`,
      );
    return result.stdout;
  }
  async ensure(keys) {
    if (!keys.length) return;
    if (!this.directory) {
      mkdirSync(join(this.root, ".local-ci-runs"), { recursive: true });
      this.directory = mkdtempSync(
        join(this.root, ".local-ci-runs/preparation-"),
      );
    }
    this.assertInputs();
    for (const key of keys) {
      if (this.failures.has(key)) {
        const error = Error(`preparation previously failed: ${key}`);
        error.blocked = key;
        throw error;
      }
      if (
        this.artifacts[key] ||
        (key.startsWith("check:") && this.checks.has(key.slice(6))) ||
        (key.startsWith("node:") && this.nodes.has(key.slice(5)))
      ) {
        if (!key.startsWith("check:"))
          preparedArtifact(key, this.root, this.env);
        continue;
      }
      const start = performance.now();
      try {
        const details = await this.prepare(key);
        this.assertInputs();
        this.onPrepared({
          key,
          ...details,
          durationMs: performance.now() - start,
        });
      } catch (error) {
        this.failures.set(key, error);
        throw error;
      }
    }
  }
  record(key, path) {
    this.artifacts[key] = { path, digest: treeDigest(path) };
  }
  async buildRust(args, targets, directory = this.directory) {
    this.requireTools(["rustc", "cargo"]);
    const stdout = await this.command(
      "cargo",
      [
        "build",
        "--locked",
        "--message-format=json-render-diagnostics",
        ...args,
      ],
      true,
    );
    const messages = stdout
      .split("\n")
      .filter((line) => line.startsWith("{"))
      .map((line) => JSON.parse(line));
    for (const [key, name, kind] of targets) {
      const artifact = messages.find(
        (item) =>
          item.reason === "compiler-artifact" &&
          item.target.name === name &&
          item.target.kind.includes(kind) &&
          item.executable,
      );
      if (!artifact) throw Error(`Cargo did not produce ${name}`);
      const path = join(
        directory,
        key + (process.platform === "win32" ? ".exe" : ""),
      );
      copyFileSync(artifact.executable, path);
      this.record(key, path);
    }
  }
  async prepare(key) {
    if (helpers[key]) {
      const [pkg, example, features] = helpers[key];
      return this.buildRust(
        ["-p", pkg, "--example", example, ...features],
        [[key, example, "example"]],
      );
    }
    if (key.startsWith("check:")) {
      const name = key.slice(6),
        [script, requirements, args] = checks[name] ?? [];
      if (!script) throw Error(`unknown preparation: ${key}`);
      await this.ensure(requirements);
      await this.command(process.execPath, [join("scripts", script), ...args]);
      this.checks.add(name);
      return;
    }
    if (key.startsWith("node:")) {
      this.requireTools(["pnpm"]);
      const filter = key.slice(5);
      // ref: pnpm dist/pnpm.mjs@v11.4.0 (list / runRecursive).
      // pnpm owns dependency selection and topological execution; no parallel graph.
      const selected = JSON.parse(
        await this.command(
          "pnpm",
          [
            "-r",
            "--filter",
            filter === "*" ? "*" : `${filter}...`,
            "list",
            "--depth",
            "-1",
            "--json",
          ],
          true,
        ),
      ).filter((pkg) => resolve(pkg.path) !== this.root);
      if (!selected.length) throw Error(`unknown Node selection: ${filter}`);
      const existing = selected.find(
        (pkg) => this.artifacts[`node:${pkg.name}`],
      );
      if (existing)
        preparedArtifact(`node:${existing.name}`, this.root, this.env);
      const needed = selected.filter(
        (pkg) => !this.artifacts[`node:${pkg.name}`],
      );
      const names = needed.map((pkg) => pkg.name);
      if (
        names.some((name) =>
          [
            "@rss-mdm-agent/execution-bindings",
            "@rss-mdm-agent/ai-host-app",
            "@rss-mdm-agent/desktop",
          ].includes(name),
        )
      )
        await this.ensure(["check:execution"]);
      if (names.includes("@rss-mdm-agent/desktop"))
        await this.ensure(["check:selfService"]);
      if (needed.length) {
        await this.command("pnpm", [
          "-r",
          ...names.flatMap((name) => ["--filter", name]),
          "run",
          "build",
        ]);
        for (const pkg of needed) {
          this.nodes.add(pkg.name);
          this.record(`node:${pkg.name}`, join(pkg.path, "dist"));
        }
      }
      this.nodes.add(filter);
      return { nodes: names };
    }

    if (key === "native") {
      const directory = join(this.directory, "native");
      mkdirSync(directory);
      await this.buildRust(
        ["--release", "-p", "native-process", "-p", "platform-private-storage"],
        ["rss-ai-worker-launcher", "rss-private-storage"].map((name) => [
          name,
          name,
          "bin",
        ]),
        directory,
      );
      this.record(key, directory);
      return;
    }
    if (key === "worker" || key === "privateWorker") {
      await this.ensure([
        "native",
        ...(key === "worker" ? ["node:@rss-mdm-agent/ai-host"] : []),
      ]);
      // A full worker also satisfies private storage, never the reverse.
      if (key === "privateWorker" && this.artifacts.worker) {
        this.artifacts[key] = this.artifacts.worker;
        return;
      }
      const directory = join(this.directory, key);
      await this.command(process.execPath, [
        "scripts/build-worker-runtime.mjs",
        directory,
        ...(key === "privateWorker" ? ["--private-only"] : []),
      ]);
      this.record(key, directory);
      if (key === "worker")
        this.artifacts.privateWorker = this.artifacts.worker;
      return;
    }
    throw Error(`unknown preparation: ${key}`);
  }
  close() {
    if (this.directory)
      rmSync(this.directory, { recursive: true, force: true });
  }
}
// Called immediately before publishing a deliverable, as well as after callbacks.
export function assertPreparedRun(signal, directory = root, env = process.env) {
  if (signal?.aborted) throw Error("preparation cancelled");
  preparedContext(directory, env);
}
// ref: Node.js v24 explicit resource management / Symbol.asyncDispose.
// The existing runner owns this scope; disposal verifies inputs and releases its artifacts.
export async function prepareRun(keys, { directory = root, ...options } = {}) {
  const controller = new AbortController();
  const interrupt = () => controller.abort("SIGINT"),
    terminate = () => controller.abort("SIGTERM");
  process.on("SIGINT", interrupt);
  process.on("SIGTERM", terminate);
  let preparation;
  const previous = process.env[contextKey];
  const cleanup = () => {
    if (previous === undefined) delete process.env[contextKey];
    else process.env[contextKey] = previous;
    preparation?.close();
    process.removeListener("SIGINT", interrupt);
    process.removeListener("SIGTERM", terminate);
  };
  try {
    const nested = Boolean(previous);
    let env;
    if (nested) {
      const value = preparedContext(directory);
      for (const key of keys) {
        if (key.startsWith("check:")) {
          if (!value.checks.includes(key.slice(6)))
            throw Error(`missing prepared check: ${key}`);
        } else preparedArtifact(key, directory);
      }
      env = { ...process.env };
      // Descendants do not borrow lease descriptors that pnpm/Node do not inherit.
      delete env._AGENT_BUILD_LEASE;
    } else {
      preparation = new Preparation(directory, {
        ...options,
        signal: controller.signal,
      });
      await preparation.ensure(keys);
      env = preparation.env;
      process.env[contextKey] = env[contextKey];
    }
    const assertReady = () =>
      assertPreparedRun(controller.signal, directory, env);
    return {
      env,
      signal: controller.signal,
      nested,
      assertReady,
      async [Symbol.asyncDispose]() {
        try {
          assertReady();
        } finally {
          cleanup();
        }
      },
    };
  } catch (error) {
    cleanup();
    throw error;
  }
}
export async function withPreparation(keys, callback, options) {
  await using run = await prepareRun(keys, options);
  return await callback(run.env, run.signal, run.nested, run.assertReady);
}
