export function treeDigest(path) {
  const digest = createHash("sha256");
  function visit(current, name) {
    const stat = lstatSync(current);
    digest.update(name + "\0");
    if (stat.isDirectory()) {
      digest.update("dir\0");
      for (const child of readdirSync(current).sort())
        visit(join(current, child), `${name}/${child}`);
    } else if (stat.isFile()) digest.update(readFileSync(current));
    else if (stat.isSymbolicLink())
      digest.update(`link\0${readlinkSync(current)}`);
    else throw Error(`unsupported prepared input: ${current}`);
  }
  visit(path, ".");
  return digest.digest("hex");
}
// Source bytes, including dirty/untracked inputs; outputs and dependency caches are excluded.
export function sourceDigest(directory) {
  const digest = createHash("sha256");
  function visit(name) {
    const path = join(directory, name);
    if (!existsSync(path)) {
      digest.update(`${name}\0missing\0`);
      return;
    }
    const stat = lstatSync(path);
    digest.update(name + "\0");
    if (stat.isDirectory()) {
      for (const child of readdirSync(path).sort()) {
        if (
          [
            "node_modules",
            "dist",
            "target",
            "gen",
            "autogenerated",
            "ai-host-runtime",
            "__pycache__",
          ].includes(child) ||
          child.endsWith(".tsbuildinfo")
        )
          continue;
        visit(`${name}/${child}`);
      }
    } else if (stat.isFile()) digest.update(readFileSync(path));
    else if (stat.isSymbolicLink())
      digest.update(`link\0${readlinkSync(path)}`);
  }
  for (const name of [
    "Cargo.toml",
    "Cargo.lock",
    "rust-toolchain.toml",
    "package.json",
    "pnpm-lock.yaml",
    "pnpm-workspace.yaml",
    "tsconfig.json",
    "vitest.config.ts",
    ".npmrc",
    ".cargo",
    ".config",
    "schemas",
    "crates",
    "vendor",
    "packages",
    "apps",
    "scripts",
    "tests",
    "apps/desktop/src-tauri/resources/ai-host-runtime/manifest.json",
  ])
    visit(name);
  return digest.digest("hex");
}
function configuration(directory, env) {
  const inputs = Object.keys(env)
    .filter(
      (key) =>
        /^(CARGO_|RUST|TAURI_|VITE_)/.test(key) ||
        [
          "NODE_OPTIONS",
          "NODE_ENV",
          "RSS_BUILD_MDM_ORGANIZATION",
          "RSS_DESKTOP_ASSEMBLY",
        ].includes(key),
    )
    .sort();
  return JSON.stringify({
    target: cargoTargetDir(realpathSync(directory), env),
    ...Object.fromEntries(inputs.map((key) => [key, env[key]])),
  });
}
function toolchain(directory, env) {
  const read = (command, args) =>
    execFileSync(command, args, {
      cwd: directory,
      env,
      encoding: "utf8",
    }).trim();
  return {
    node: process.versions.node,
    pnpm: read("pnpm", ["--version"]),
    rustc: read("rustc", ["-vV"]),
    cargo: read("cargo", ["-V"]),
  };
}
export function preparedContext(directory = root, env = process.env) {
  if (!env[contextKey])
    throw Error("prepared inputs required; use the owning pnpm/CI entry");
  const value = JSON.parse(env[contextKey]);
  if (
    value.root !== realpathSync(directory) ||
    !Number.isSafeInteger(value.owner) ||
    value.owner < 1 ||
    !existsSync(value.directory) ||
    dirname(value.directory) !== join(value.root, ".local-ci-runs")
  )
    throw Error("invalid or expired preparation context");
  try {
    process.kill(value.owner, 0);
  } catch {
    throw Error("preparation owner has exited");
  }
  if (
    value.config !== configuration(directory, env) ||
    value.source !== sourceDigest(directory)
  )
    throw Error("prepared inputs changed; start a new run");
  if (JSON.stringify(value.tools) !== JSON.stringify(toolchain(directory, env)))
    throw Error("prepared toolchain changed; start a new run");
  return value;
}
export function preparedArtifact(key, directory = root, env = process.env) {
  const value = preparedContext(directory, env);
  if (key === "node:*") {
    for (const name of packages(directory).keys()) {
      const artifact = value.artifacts[`node:${name}`];
      if (
        !value.nodes.includes(name) ||
        !artifact ||
        !existsSync(artifact.path) ||
        treeDigest(artifact.path) !== artifact.digest
      )
        throw Error(`missing or changed prepared Node package: ${name}`);
    }
    return directory;
  }
  const artifact = value.artifacts[key];
  if (
    !artifact ||
    !existsSync(artifact.path) ||
    treeDigest(artifact.path) !== artifact.digest
  )
    throw Error(`missing or changed prepared artifact: ${key}`);
  return artifact.path;
}
export function preparedCheck(key, directory = root, env = process.env) {
  const value = preparedContext(directory, env);
  return value.checks.includes(key);
}
function packages(directory) {
  const result = new Map();
  function visit(path) {
    for (const entry of readdirSync(path, { withFileTypes: true })) {
      if (
        !entry.isDirectory() ||
        ["node_modules", "dist", "src-tauri"].includes(entry.name)
      )
        continue;
      const child = join(path, entry.name),
        manifest = join(child, "package.json");
      if (existsSync(manifest)) {
        const pkg = JSON.parse(readFileSync(manifest));
        result.set(pkg.name, { ...pkg, path: child });
      } else visit(child);
    }
  }
  for (const name of ["apps", "packages"]) visit(join(directory, name));
  return result;
}
export class Preparation {
  constructor(
    directory = root,
    {
      env = process.env,
      signal,
      execute = runCommand,
      onPrepared = () => {},
    } = {},
  ) {
    this.root = realpathSync(directory);
    this.baseEnv = { ...env };
    delete this.baseEnv[contextKey];
    this.signal = signal;
    this.execute = execute;
    this.onPrepared = onPrepared;
    this.artifacts = {};
    this.nodes = new Set();
    this.checks = new Set();
    this.failures = new Map();
    this.directory = undefined;
    this.source = sourceDigest(directory);
    this.config = configuration(directory, this.baseEnv);
  }
  get env() {
    return {
      ...this.baseEnv,
      [contextKey]: JSON.stringify({
        root: this.root,
        owner: process.pid,
        directory: this.directory,
        source: this.source,
        config: this.config,
        tools: this.tools,
        artifacts: this.artifacts,
        nodes: [...this.nodes],
        checks: [...this.checks],
      }),
    };
  }
  assertInputs() {
    if (this.signal?.aborted) throw Error("preparation cancelled");
    if (
      sourceDigest(this.root) !== this.source ||
      configuration(this.root, this.baseEnv) !== this.config
    )
      throw Error("inputs changed during preparation/run");
    if (
      this.tools &&
      JSON.stringify(toolchain(this.root, this.baseEnv)) !==
        JSON.stringify(this.tools)
    )
      throw Error("toolchain changed during preparation/run");
  }
  async command(command, args, capture = false, env = this.env) {
    const result = await this.execute(command, args, {
      cwd: this.root,
      env,
      stdio: "inherit",
      signal: this.signal,
      capture,
    });
    if (result.status !== 0)
      throw Error(
        `${command} ${args.join(" ")}: ${result.error?.message ?? result.signal ?? result.status}`,
      );
    return result.stdout;
  }
  async ensure(keys) {
    if (!keys.length) return;
    if (!this.directory) {
      mkdirSync(join(this.root, ".local-ci-runs"), { recursive: true });
      this.directory = mkdtempSync(
        join(this.root, ".local-ci-runs/preparation-"),
      );
      this.tools = toolchain(this.root, this.baseEnv);
      const manifest = JSON.parse(
        readFileSync(join(this.root, "package.json")),
      );
      if (
        this.tools.node !== manifest.engines.node ||
        `pnpm@${this.tools.pnpm}` !== manifest.packageManager
      )
        throw Error("preparation requires the pinned Node/pnpm toolchain");
    }
    this.assertInputs();
    for (const key of keys) {
      if (this.failures.has(key)) {
        const error = Error(`preparation previously failed: ${key}`);
        error.blocked = key;
        throw error;
      }
      if (
        this.artifacts[key] ||
        (key.startsWith("check:") && this.checks.has(key.slice(6))) ||
        (key.startsWith("node:") && this.nodes.has(key.slice(5)))
      )
        continue;
      const start = performance.now();
      try {
        const details = await this.prepare(key);
        this.assertInputs();
        this.onPrepared({
          key,
          ...details,
          durationMs: performance.now() - start,
        });
      } catch (error) {
        this.failures.set(key, error);
        throw error;
      }
    }
  }
  record(key, path) {
    this.artifacts[key] = { path, digest: treeDigest(path) };
  }
  async prepare(key) {
    if (helpers[key]) {
      const [pkg, example, features] = helpers[key];
      const stdout = await this.command(
        "cargo",
        [
          "build",
          "--locked",
          "--message-format=json",
          "-p",
          pkg,
          "--example",
          example,
          ...features,
        ],
        true,
      );
      const artifact = stdout
        .split("\n")
        .filter((line) => line.startsWith("{"))
        .map((line) => JSON.parse(line))
        .find(
          (item) =>
            item.reason === "compiler-artifact" &&
            item.target.name === example &&
            item.target.kind.includes("example") &&
            item.executable,
        );
      if (!artifact) throw Error(`Cargo did not produce ${example}`);
      const path = join(
        this.directory,
        key + (process.platform === "win32" ? ".exe" : ""),
      );
      copyFileSync(artifact.executable, path);
      this.record(key, path);
      return;
    }
    if (key.startsWith("check:")) {
      const name = key.slice(6),
        [script, requirements, args] = checks[name] ?? [];
      if (!script) throw Error(`unknown preparation: ${key}`);
      await this.ensure(requirements);
      await this.command(process.execPath, [join("scripts", script), ...args]);
      this.checks.add(name);
      return;
    }
    if (key.startsWith("node:")) {
      const graph = packages(this.root),
        needed = new Set();
      const visit = (name) => {
        if (needed.has(name) || this.nodes.has(name)) return;
        const pkg = graph.get(name);
        if (!pkg) throw Error(`unknown Node package: ${name}`);
        needed.add(name);
        for (const field of [
          "dependencies",
          "devDependencies",
          "peerDependencies",
          "optionalDependencies",
        ])
          for (const dependency of Object.keys(pkg[field] ?? {}))
            if (graph.has(dependency)) visit(dependency);
      };
      if (key === "node:*") for (const name of graph.keys()) visit(name);
      else visit(key.slice(5));
      if (
        needed.has("@rss-mdm-agent/execution-bindings") ||
        needed.has("@rss-mdm-agent/ai-host-app") ||
        needed.has("@rss-mdm-agent/desktop")
      )
        await this.ensure(["check:execution"]);
      if (needed.has("@rss-mdm-agent/desktop"))
        await this.ensure(["check:selfService"]);
      if (!needed.size) return;
      await this.command("pnpm", [
        ...[...needed].flatMap((name) => ["--filter", name]),
        "run",
        "compile",
      ]);
      for (const name of needed) {
        this.nodes.add(name);
        this.record(`node:${name}`, join(graph.get(name).path, "dist"));
      }
      return { nodes: [...needed] };
    }
    if (key === "native") {
      const stdout = await this.command(
        "cargo",
        [
          "build",
          "--release",
          "--locked",
          "--message-format=json",
          "-p",
          "native-process",
          "-p",
          "platform-private-storage",
        ],
        true,
      );
      const messages = stdout
        .split("\n")
        .filter((line) => line.startsWith("{"))
        .map((line) => JSON.parse(line));
      const directory = join(this.directory, "native");
      mkdirSync(directory);
      for (const name of ["rss-ai-worker-launcher", "rss-private-storage"]) {
        const artifact = messages.find(
          (item) =>
            item.reason === "compiler-artifact" &&
            item.target.name === name &&
            item.executable,
        );
        if (!artifact) throw Error(`Cargo did not produce ${name}`);
        const path = join(
          directory,
          name + (process.platform === "win32" ? ".exe" : ""),
        );
        copyFileSync(artifact.executable, path);
        this.record(name, path);
      }
      this.record(key, directory);
      return;
    }
    if (key === "worker" || key === "privateWorker") {
      await this.ensure([
        "native",
        ...(key === "worker" ? ["node:@rss-mdm-agent/ai-host"] : []),
      ]);
      // A full worker also satisfies private storage, never the reverse.
      if (key === "privateWorker" && this.artifacts.worker) {
        this.artifacts[key] = this.artifacts.worker;
        return;
      }
      const directory = join(this.directory, key);
      await this.command(process.execPath, [
        "scripts/build-worker-runtime.mjs",
        directory,
        ...(key === "privateWorker" ? ["--private-only"] : []),
      ]);
      this.record(key, directory);
      if (key === "worker")
        this.artifacts.privateWorker = this.artifacts.worker;
      return;
    }
    throw Error(`unknown preparation: ${key}`);
  }
  close() {
    if (this.directory)
      rmSync(this.directory, { recursive: true, force: true });
  }
}
export async function withPreparation(
  keys,
  callback,
  { directory = root, allowSourceChanges = false } = {},
) {
  if (process.env[contextKey]) {
    const value = preparedContext(directory);
    for (const key of keys) {
      if (key.startsWith("check:")) {
        if (!value.checks.includes(key.slice(6)))
          throw Error(`missing prepared check: ${key}`);
      } else preparedArtifact(key, directory);
    }
    const env = { ...process.env };
    // The CI owner holds its lease; descendants do not borrow descriptors that
    // pnpm/Node test subprocesses do not inherit.
    delete env._AGENT_BUILD_LEASE;
    return callback(env, undefined, true);
  }
  const controller = new AbortController();
  const interrupt = () => controller.abort("SIGINT"),
    terminate = () => controller.abort("SIGTERM");
  process.on("SIGINT", interrupt);
  process.on("SIGTERM", terminate);
  const preparation = new Preparation(directory, { signal: controller.signal });
  const previous = process.env[contextKey];
  try {
    await preparation.ensure(keys);
    process.env[contextKey] = preparation.env[contextKey];
    const result = await callback(preparation.env, controller.signal, false);
    if (!allowSourceChanges) preparation.assertInputs();
    if (controller.signal.aborted)
      return controller.signal.reason === "SIGINT" ? 130 : 143;
    return result;
  } finally {
    if (previous === undefined) delete process.env[contextKey];
    else process.env[contextKey] = previous;
    preparation.close();
    process.removeListener("SIGINT", interrupt);
    process.removeListener("SIGTERM", terminate);
  }
}
