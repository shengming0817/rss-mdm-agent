import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import assert from "node:assert/strict";
import { format, resolveConfig } from "prettier";
const root = fileURLToPath(new URL("../", import.meta.url));
const raw = execFileSync(
  "cargo",
  [
    "run",
    "--quiet",
    "--locked",
    "-p",
    "rss-mdm-desktop",
    "--example",
    "self-service-preview",
    "--no-default-features",
  ],
  { cwd: root, encoding: "utf8" },
);
const generated = JSON.parse(raw);
if (process.argv.includes("--write")) {
  const file = fileURLToPath(
    new URL("../apps/desktop/src/self-service/preview.ts", import.meta.url),
  );
  writeFileSync(
    file,
    await format(
      `// Generated by scripts/check-self-service.mjs --write; Rust owns these fixtures.\nimport type { Snapshot } from "./types";\nconst snapshot: Snapshot = ${raw.trim()};\nexport default snapshot;\n`,
      { ...(await resolveConfig(file)), filepath: file },
    ),
  );
} else {
  const { default: committed } = await import(
    "../apps/desktop/src/self-service/preview.ts"
  );
  assert.deepEqual(
    committed,
    generated,
    "browser read-only preview must match the explicit Rust fixture projection",
  );
  console.log("Self-service: Rust/browser fixture parity passed");
}
