// ref: schemars 1.2.2 src/generate.rs; json-schema-to-typescript 16.0.0 src/index.ts.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import { format } from "prettier";
const root = fileURLToPath(new URL("../", import.meta.url));
const run = (example, crate = "execution-app") =>
  JSON.parse(
    execFileSync(
      "cargo",
      ["run", "--quiet", "--locked", "-p", crate, "--example", example],
      { cwd: root, encoding: "utf8" },
    ),
  );
const schema = run("task-details-schema");
const binding = await format(
  await compile(schema, "ExecutionTaskDetails", {
    bannerComment:
      "// Generated by scripts/check-execution-bindings.mjs --write; edit Rust owners instead.",
    additionalProperties: false,
    unreachableDefinitions: true,
    maxItems: -1,
  }),
  { parser: "typescript", printWidth: 80 },
);
const fixtures = await format(JSON.stringify(run("task-details-fixtures")), {
  parser: "json",
});
const files = [
  [
    "apps/ai-host/src/execution-tools.json",
    await format(JSON.stringify(run("tool-schema", "execution-mcp")), {
      parser: "json",
    }),
  ],
  ["apps/desktop/src/assistant/execution-types.ts", binding],
  ["tests/assistant/execution-fixtures.json", fixtures],
];
for (const [name, content] of files) {
  const path = new URL(`../${name}`, import.meta.url);
  if (process.argv.includes("--write")) {
    mkdirSync(new URL(".", path), { recursive: true });
    writeFileSync(path, content);
  } else if (readFileSync(path, "utf8") !== content)
    throw new Error(
      `Execution binding/fixture drift: ${name}; regenerate and review Rust owner changes`,
    );
}
console.log("Execution task bindings and SQLite-backed S1 fixtures match");
