// ref: schemars 1.2.2 src/generate.rs; json-schema-to-typescript 16.0.0 src/index.ts.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import { format } from "prettier";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { Ajv2020 } = require("ajv/dist/2020.js");
const standalone = require("ajv/dist/standalone/index.js").default;
const root = fileURLToPath(new URL("../", import.meta.url));
const run = (example, crate = "execution-app") =>
  JSON.parse(
    execFileSync(
      "cargo",
      ["run", "--quiet", "--locked", "-p", crate, "--example", example],
      { cwd: root, encoding: "utf8" },
    ),
  );
const schema = run("task-details-schema");
const binding = await format(
  await compile(schema, "BackendTaskView", {
    bannerComment:
      "// Generated by scripts/check-execution-bindings.mjs --write; edit Rust owners instead.",
    additionalProperties: false,
    unreachableDefinitions: true,
    maxItems: -1,
  }),
  { parser: "typescript", printWidth: 80 },
);
const fixtures = await format(JSON.stringify(run("task-details-fixtures")), {
  parser: "json",
});
const tools = run("tool-schema", "execution-mcp");
const generated = "packages/execution-bindings/src";
const files = [
  [
    `${generated}/tools.json`,
    await format(JSON.stringify(tools), {
      parser: "json",
    }),
  ],
  [`${generated}/task-details.ts`, binding],
  ["tests/assistant/execution-fixtures.json", fixtures],
];
for (const [name, type, file] of [
  ["execution_execute", "BackendSelection", "execute"],
  ["execution_status", "OperationRequest", "operation"],
]) {
  const schema = tools.find((tool) => tool.name === name).inputSchema;
  files.push([
    `${generated}/${file === "execute" ? "execute-input" : "operation-request"}.ts`,
    await format(
      await compile(schema, type, {
        bannerComment:
          "// Generated by scripts/check-execution-bindings.mjs --write; edit Rust owners instead.",
        additionalProperties: false,
        maxItems: -1,
      }),
      { parser: "typescript" },
    ),
  ]);
  // ref: AJV standalone: compile at build time; no evaluator or AJV runtime in the browser.
  const ajv = new Ajv2020({
    strict: true,
    validateFormats: false,
    code: { source: true, esm: true },
  });
  let validator = standalone(ajv, ajv.compile(schema));
  const helpers = new Map();
  validator = validator.replace(
    /require\("(ajv\/dist\/runtime\/[^" ]+)"\)\.default/g,
    (_, path) => {
      if (!helpers.has(path)) helpers.set(path, `helper${helpers.size}`);
      return helpers.get(path);
    },
  );
  validator =
    "// @ts-nocheck\n// Generated from Rust execution-mcp schema. Do not edit.\n" +
    [...helpers]
      .map(
        ([path, name]) =>
          `const ${name} = ${require(path).default.toString()};`,
      )
      .join("\n") +
    "\n" +
    validator;
  files.push([
    `${generated}/validate-${file}.ts`,
    await format(validator, { parser: "typescript" }),
  ]);
}
for (const [name, content] of files) {
  const path = new URL(`../${name}`, import.meta.url);
  if (process.argv.includes("--write")) {
    mkdirSync(new URL(".", path), { recursive: true });
    writeFileSync(path, content);
  } else if (readFileSync(path, "utf8") !== content)
    throw new Error(
      `Execution binding/fixture drift: ${name}; regenerate and review Rust owner changes`,
    );
}
console.log("Execution task bindings and SQLite-backed S1 fixtures match");
