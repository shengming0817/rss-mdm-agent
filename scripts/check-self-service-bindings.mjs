import { helperOutput, checkAlreadyPrepared } from "./preparation.mjs";
// ref: json-schema-to-typescript src/index.ts@7f72770eb854328c96b112be445da0306bebdbaf (16.0.0)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import { typescriptSchema } from "./typescript-schema.mjs";
import { format } from "prettier";
const root = fileURLToPath(new URL("../", import.meta.url));
if (!process.argv.includes("--write") && checkAlreadyPrepared("selfService"))
  process.exit(0);
const schema = JSON.parse(await helperOutput("selfServiceSchema"));
const binding = await compile(typescriptSchema(schema), "SelfServiceCommands", {
  bannerComment:
    "// Generated by scripts/check-self-service-bindings.mjs --write; edit Rust owners instead.",
  additionalProperties: false,
  unreachableDefinitions: true,
  maxItems: -1,
});
const generated = await format(
  `${binding}
export type DataAccessPort = {
  [K in keyof SelfServiceCommands as K extends \`query_\${string}\` | "data_read" ? K : never]:
    (input: SelfServiceCommands[K]["input"]) => Promise<SelfServiceCommands[K]["output"]>;
};
export type SelfServicePort = {
  [K in keyof SelfServiceCommands as K extends \`self_service_\${infer M}\` ? M : never]:
    SelfServiceCommands[K]["input"] extends null ? () => Promise<SelfServiceCommands[K]["output"]> :
    (input: SelfServiceCommands[K]["input"]) => Promise<SelfServiceCommands[K]["output"]>;
};
`,
  { parser: "typescript", printWidth: 80 },
);
const path = new URL(
  "../apps/desktop/src/self-service/types.ts",
  import.meta.url,
);
if (process.argv.includes("--write")) writeFileSync(path, generated);
else if (readFileSync(path, "utf8") !== generated)
  throw new Error(
    "Self-service bindings drifted; run node scripts/check-self-service-bindings.mjs --write and review the Rust/TypeScript change",
  );
else console.log("Self-service: Rust/TypeScript command bindings match");
